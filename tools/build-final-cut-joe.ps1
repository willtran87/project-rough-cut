$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Speech
$finaleRepo = Split-Path $PSScriptRoot -Parent
$finaleSource = Join-Path $finaleRepo 'assets/audio/final-cut-joe'
$finaleRuntime = Join-Path $finaleRepo 'web/assets/audio/final-cut-joe'
New-Item -ItemType Directory -Force -Path $finaleRuntime | Out-Null
$finaleLines = Get-Content -LiteralPath (Join-Path $finaleSource 'script.json') -Raw | ConvertFrom-Json
$finaleSpeaker = New-Object System.Speech.Synthesis.SpeechSynthesizer
$finaleManifest = @()
try {
  $finaleSpeaker.SelectVoice('Microsoft David Desktop')
  $finaleSpeaker.Rate = -1
  $finaleSpeaker.Volume = 100
  foreach ($finaleLine in $finaleLines) {
    if ($finaleLine.id -notmatch '^[a-z-]+$') { throw 'Invalid dialogue file ID' }
    $finaleWav = Join-Path $finaleSource ($finaleLine.id + '-source.wav')
    $finaleClip = Join-Path $finaleRuntime ($finaleLine.id + '.ogg')
    $finaleSpeaker.SetOutputToWaveFile($finaleWav)
    $finaleSpeaker.Speak($finaleLine.text)
    $finaleSpeaker.SetOutputToNull()
    & ffmpeg -hide_banner -loglevel error -y -i $finaleWav -af 'highpass=f=220,lowpass=f=3200,loudnorm=I=-21:TP=-3:LRA=4' -c:a libopus -b:a 48k $finaleClip
    if ($LASTEXITCODE -ne 0) { throw 'Final Cut dialogue encoding failed' }
    $finaleProbe = (& ffprobe -v error -show_entries format=duration -of json $finaleClip | ConvertFrom-Json)
    if ($LASTEXITCODE -ne 0) { throw 'Final Cut dialogue inspection failed' }
    $finaleManifest += [ordered]@{id=$finaleLine.id;text=$finaleLine.text;priority=$finaleLine.priority;window=$finaleLine.window;essential=$finaleLine.essential;duration=[Math]::Round([double]$finaleProbe.format.duration,3);url=('./assets/audio/final-cut-joe/' + $finaleLine.id + '.ogg')}
  }
} finally { $finaleSpeaker.Dispose() }
$finaleJson = ConvertTo-Json -InputObject $finaleManifest -Depth 5 -Compress
[IO.File]::WriteAllText((Join-Path $finaleRepo 'web/final-cut-dialogue-lines.js'),"// Generated by tools/build-final-cut-joe.ps1 from the authored script.`nexport const JOE_LINES = $finaleJson;`n")
$finaleManifest | ForEach-Object { [pscustomobject]$_ } | Select-Object id,duration,url
