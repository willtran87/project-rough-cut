$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Speech
$paRepo = Split-Path $PSScriptRoot -Parent
$paSource = Join-Path $paRepo 'assets/audio/final-cut-pa'
$paRuntime = Join-Path $paRepo 'web/assets/audio/final-cut-pa'
New-Item -ItemType Directory -Force -Path $paSource,$paRuntime | Out-Null
$paSpeaker = New-Object System.Speech.Synthesis.SpeechSynthesizer
$paManifest = @()
try {
  $paSpeaker.SelectVoice('Microsoft David Desktop')
  $paSpeaker.Rate = 0
  $paSpeaker.Volume = 100
  foreach ($paMask in 0..7) {
    $paWords = @('Final round. Associate analyst.')
    if ($paMask -band 1) { $paWords += 'Audit bell filed.' }
    if ($paMask -band 2) { $paWords += 'Field log received.' }
    if ($paMask -band 4) { $paWords += 'Release review signed.' }
    if ($paMask -eq 0) { $paWords += 'Your final round is ready.' }
    $paWords += 'Acceptance is everything.'
    $paText = $paWords -join ' '
    $paId = 'pa-' + $paMask
    $paWav = Join-Path $paSource ($paId + '-source.wav')
    $paClip = Join-Path $paRuntime ($paId + '.ogg')
    $paSpeaker.SetOutputToWaveFile($paWav)
    $paSpeaker.Speak($paText)
    $paSpeaker.SetOutputToNull()
    & ffmpeg -hide_banner -loglevel error -y -i $paWav -af 'highpass=f=350,lowpass=f=2600,loudnorm=I=-22:TP=-3:LRA=4' -c:a libopus -b:a 40k $paClip
    if ($LASTEXITCODE -ne 0) { throw 'Final Cut PA encoding failed' }
    # Ogg container timestamps can outlast the decoded samples. The browser
    # plays sample frames, so derive its clock from the actual decoded count.
    $paFrames = & ffprobe -v error -select_streams a:0 -show_entries frame=nb_samples -of csv=p=0 $paClip
    if ($LASTEXITCODE -ne 0) { throw 'Final Cut PA inspection failed' }
    $paSamples = ($paFrames | Where-Object { $_ -match '^\d+$' } | Measure-Object -Sum).Sum
    if ($paSamples -le 0) { throw 'Final Cut PA has no decoded samples' }
    $paManifest += [ordered]@{id=$paId;mask=$paMask;text=$paText;duration=[Math]::Round($paSamples / 48000,6);url=('./assets/audio/final-cut-pa/' + $paId + '.ogg')}
  }
} finally { $paSpeaker.Dispose() }
$paJson = ConvertTo-Json -InputObject $paManifest -Depth 5 -Compress
[IO.File]::WriteAllText((Join-Path $paRepo 'web/final-cut-pa-lines.js'),"// Generated by tools/build-final-cut-pa.ps1; only one matching receipt variant loads per visit.`nexport const PA_LINES = $paJson;`n")
$paManifest | ForEach-Object { [pscustomobject]$_ } | Select-Object id,duration
