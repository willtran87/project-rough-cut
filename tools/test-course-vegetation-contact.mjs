import assert from 'node:assert/strict';
import {createVegetationContact} from '../web/course-vegetation-contact.js';
const field=createVegetationContact();
const frame={time:0,player:{x:0,y:0},joe:{x:20,y:20}};
field.update(frame);
assert.equal(field.stats().contacts.filter(p=>p[3]>0).length,2);
assert(Math.abs(field.stats().contacts[3][0]-(20*.1152+.45))<1e-9,'Mower envelope follows deck offset');
field.update({...frame,time:.1,player:{x:3,y:0}});
const moving=field.stats();assert.equal(moving.contacts.filter(p=>p[3]>0).length,3);
field.update({...frame,time:.1,player:{x:6,y:0}});assert.deepEqual(field.stats(),moving,'Same simulation frame is idempotent');
field.update({...frame,time:20,paused:true});assert.deepEqual(field.stats(),moving,'Pause freezes contact recovery');
field.update({...frame,time:.5,player:{x:3,y:0}});assert(field.stats().contacts[1][3]<moving.contacts[1][3]);
field.update({...frame,time:2,player:{x:3,y:0}});assert.equal(field.stats().contacts[1][3],0);
for(let i=0;i<100;i++)field.update({...frame,time:2+i/10,player:{x:i*3,y:0}});
assert.equal(field.stats().contacts.length,6,'History remains bounded');
field.update({...frame,time:13,player:{x:-200,y:0}});assert.equal(field.stats().contacts[1][3],0,'Teleport never sweeps the course');
field.update({...frame,time:14,player:{x:-197,y:0},reducedMotion:true});assert.equal(field.stats().contacts[1][3],0);assert(field.stats().contacts[0][3]>0,'Reduced motion preserves static physical displacement');
field.update({...frame,time:0});assert.equal(field.stats().contacts[1][3],0,'Restart clears history');
field.update({time:1});assert(field.stats().contacts.every(p=>p[3]===0));
console.log(JSON.stringify({passed:true,checks:'Body contact, bounded wakes, simulation-time decay, repeat render, pause, teleport, reduced motion and restart'}));
