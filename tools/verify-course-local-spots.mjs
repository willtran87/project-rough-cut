import assert from 'node:assert/strict';
import * as T from '../web/vendor/three/three.module.js';
import {createLocalLightCulling,stableLightMaterialSort} from '../web/local-light-culling.js';

const c=createLocalLightCulling({includeSpots:true}),g=new T.BoxGeometry(2,2,2),full=new T.MeshLambertMaterial();
g.computeBoundingBox();
const mesh=new T.Mesh(g,full);mesh.position.x=10;c.register(mesh);
const lite=c.preparation.children[0].material,spot=new T.SpotLight(0xffffff,1,4),point=new T.PointLight(0xffffff,1,4);
const shader={fragmentShader:'#include <lights_fragment_begin>'};lite.onBeforeCompile(shader);
assert(!shader.fragmentShader.includes('#if ( NUM_SPOT_LIGHTS > 0 ) && defined( RE_Direct )'));
assert(!shader.fragmentShader.includes('#if ( NUM_POINT_LIGHTS > 0 ) && defined( RE_Direct )'));
assert(shader.fragmentShader.includes('getDirectionalLightInfo'));
const item=m=>({material:m,groupOrder:0,renderOrder:0,materialVariant:0,z:1,id:1});
assert.equal(stableLightMaterialSort(item(full),item(lite)),0);
c.update([point,spot]);assert.equal(mesh.material,lite);
spot.position.x=5;c.update([point,spot]);assert.equal(mesh.material,full,'spotlight boundary retains full lighting');
spot.position.x=4.995;c.update([point,spot]);assert.equal(mesh.material,full,'safety margin');
spot.position.x=4.9;c.update([point,spot]);assert.equal(mesh.material,lite);
spot.position.x=10;spot.intensity=0;c.update([point,spot]);assert.equal(mesh.material,lite);
spot.intensity=-1;c.update([point,spot]);assert.equal(mesh.material,full,'nonzero signed power remains active');
spot.intensity=1;spot.visible=false;c.update([point,spot]);assert.equal(mesh.material,lite);
spot.visible=true;spot.distance=0;spot.position.x=100;c.update([point,spot]);assert.equal(mesh.material,full,'unbounded spotlight');
spot.distance=Infinity;c.update([point,spot]);assert.equal(mesh.material,full,'nonfinite reach fails open');
spot.distance=4;point.position.x=10;c.update([point,spot]);assert.equal(mesh.material,full,'point source still retained');
point.position.x=0;
const parent=new T.Group();parent.position.x=10;parent.add(spot);spot.position.x=0;
c.update([point,spot]);assert.equal(mesh.material,full,'transformed spot origin');
parent.position.x=100;c.update([point,spot]);assert.equal(mesh.material,lite);
mesh.visible=false;parent.position.x=10;c.update([point,spot]);mesh.visible=true;c.update([point,spot]);assert.equal(mesh.material,full,'camera reveal');
let disposed=0;lite.addEventListener('dispose',()=>disposed++);c.dispose();c.dispose();
assert.equal(disposed,1);assert.equal(mesh.material,full);g.dispose();full.dispose();
console.log('PASS: point/spot reach, boundary margin, power/visibility, unbounded sources, transformed origin, camera reveal, sort identity and disposal');
